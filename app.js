
import { pipeline } from "https://cdn.jsdelivr.net/npm/@huggingface/transformers";

const fileInput = document.getElementById("fileInput");
const chooseBtn = document.getElementById("chooseBtn");
const dropZone = document.getElementById("dropZone");
const fileName = document.getElementById("fileName");
const loading = document.getElementById("loading");
const preview = document.getElementById("preview");
const resultTitle = document.getElementById("resultTitle");
const statusPill = document.getElementById("statusPill");
const visionStatus = document.getElementById("visionStatus");
const visionMessage = document.getElementById("visionMessage");
const chips = document.getElementById("chips");
const signals = document.getElementById("signals");

let detectorPromise;

function getDetector() {
  if (!detectorPromise) {
    detectorPromise = pipeline(
      "zero-shot-image-classification",
      "Xenova/clip-vit-base-patch32"
    );
  }
  return detectorPromise;
}

chooseBtn.addEventListener("click", event => {
  event.stopPropagation();
  fileInput.click();
});

dropZone.addEventListener("click", () => fileInput.click());

["dragenter", "dragover"].forEach(type => {
  dropZone.addEventListener(type, event => {
    event.preventDefault();
    dropZone.classList.add("drag");
  });
});

["dragleave", "drop"].forEach(type => {
  dropZone.addEventListener(type, event => {
    event.preventDefault();
    dropZone.classList.remove("drag");
  });
});

dropZone.addEventListener("drop", event => {
  const file = event.dataTransfer.files[0];
  if (file) analyze(file);
});

fileInput.addEventListener("change", event => {
  const file = event.target.files[0];
  if (file) analyze(file);
});

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#039;"
  }[char]));
}

function showSignals(items) {
  signals.innerHTML = items.map(item => `
    <div class="signal">
      <div class="signal-icon">${item.icon}</div>
      <div>
        <b>${escapeHtml(item.title)}</b>
        <p>${escapeHtml(item.text)}</p>
      </div>
    </div>
  `).join("");
}

async function analyze(file) {
  if (!file.type.startsWith("image/")) {
    visionMessage.textContent = "Selecione um arquivo de imagem válido.";
    return;
  }

  fileName.textContent = `Arquivo: ${file.name}`;
  preview.innerHTML = "";

  const imageUrl = URL.createObjectURL(file);
  const img = document.createElement("img");
  img.src = imageUrl;
  img.alt = "Imagem selecionada";
  preview.appendChild(img);

  loading.classList.remove("hidden");
  resultTitle.textContent = "Carregando o modelo...";
  statusPill.textContent = "Analisando";
  visionStatus.textContent = "Modelo de visão";
  visionMessage.textContent =
    "Na primeira utilização, o modelo precisa ser baixado. Aguarde.";
  chips.innerHTML = "";
  signals.innerHTML = "";

  try {
    const detector = await getDetector();

    resultTitle.textContent = "Comparando características visuais...";

    const labels = [
      "A natural photograph taken by a camera",
      "An image generated by artificial intelligence",
      "A digitally manipulated or edited photograph"
    ];

    const results = await detector(file, labels);
    results.sort((a, b) => b.score - a.score);

    const best = results[0];
    const score = Math.round(best.score * 100);
    const isAI = best.label === labels[1];
    const isEdited = best.label === labels[2];

    const classification = isAI
      ? "Possíveis características de imagem gerada por IA"
      : isEdited
        ? "Possíveis características de imagem editada"
        : "Características semelhantes às de uma fotografia";

    resultTitle.textContent = classification;
    statusPill.textContent = "Análise concluída";
    visionStatus.textContent = "Triagem experimental";

    visionMessage.textContent =
      `Pontuação comparativa do modelo: ${score}%. ` +
      "Esse valor não é uma probabilidade calibrada nem comprova a origem da imagem.";

    chips.innerHTML = results.map(result => `
      <span class="chip">
        ${escapeHtml(result.label)}: ${Math.round(result.score * 100)}%
      </span>
    `).join("");

    showSignals([
      {
        icon: "◉",
        title: "Principal correspondência",
        text: `O modelo encontrou maior semelhança com: ${best.label}.`
      },
      {
        icon: "％",
        title: "Pontuação comparativa",
        text: `${score}% para a classe mais bem classificada. Não significa ${score}% de certeza de que a imagem seja verdadeira ou falsa.`
      },
      {
        icon: "!",
        title: "Limitação importante",
        text: "Este modelo compara conceitos visuais; não é um detector forense especializado em deepfakes. Pode errar e não identifica, por si só, a causa de cada sinal."
      },
      {
        icon: "⌘",
        title: "Dados técnicos",
        text: `${file.type || "Formato desconhecido"} · ${(file.size / (1024 * 1024)).toFixed(2)} MB`
      }
    ]);

  } catch (error) {
    console.error(error);
    resultTitle.textContent = "Não foi possível concluir a análise";
    statusPill.textContent = "Erro";
    visionStatus.textContent = "Falha ao carregar";
    visionMessage.textContent =
      "Verifique a conexão com a internet e tente novamente. O modelo precisa ser baixado para funcionar.";
  } finally {
    loading.classList.add("hidden");
    URL.revokeObjectURL(imageUrl);
  }
}
